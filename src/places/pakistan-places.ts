// the spellings used to merge misspelled cities / neighbourhoods into one
// name ("Faislabad" → "Faisalabad", "gulshan e iqbal" → "Gulshan-e-Iqbal").
// This is a starting list. Admins can extend it (add areas or aliases here);
// the app also adds the programme's own neighbourhoods to each city automatically.

export interface Place { name: string; aliases?: string[] }
export interface CityPlaces extends Place { district: string; province: string; areas: Place[] }
export interface ProvinceDistricts { province: string; districts: Place[] }

/** A place with optional alternative spellings. */
const p = (name: string, ...aliases: string[]): Place => (aliases.length ? { name, aliases } : { name });

/** An Islamabad sector ("F-7") with its usual typed forms ("F7", "F 7"). */
const sector = (name: string): Place => p(name, name.replace('-', ''), name.replace('-', ' '));

